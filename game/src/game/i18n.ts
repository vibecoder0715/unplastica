export function getGameString(key: string, lang: GameLanguage = 'English'): string {
  const dict = GAME_STRINGS[lang] || GAME_STRINGS.English;
  return dict[key] || GAME_STRINGS.English[key] || key;
}

export function getLocalizedAssetName(id: string, defaultName: string, lang: GameLanguage = 'English'): string {
  if (lang === '中文') return ASSET_NAMES_ZH[id] || defaultName;
  if (lang === 'Bahasa Melayu') return ASSET_NAMES_BM[id] || defaultName;
  return defaultName;
}

