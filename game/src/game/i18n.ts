export function getShortDescriptionWithBold(
  id: string,
  defaultSentences: [string, string],
  lang: GameLanguage = 'English'
): string {
  if (lang === '中文' && DESCRIPTIONS_ZH[id]) return DESCRIPTIONS_ZH[id];
  if (lang === 'Bahasa Melayu' && DESCRIPTIONS_BM[id]) return DESCRIPTIONS_BM[id];
  if (DESCRIPTIONS_EN[id]) return DESCRIPTIONS_EN[id];

  // Clean fallback: take first sentence, trim to ~12 words and bold subject
  const text = defaultSentences?.[0] || 'A native Malaysian wildlife species.';
  const parts = text.split('.');
  const first = parts[0]?.trim() || text;
  return `<b>${first}</b>`;
}
