export function getShortDescriptionWithBold(
  id: string,
  defaultSentences: [string, string],
  lang: GameLanguage = 'English'
): string {
  if (lang === 'தமிழ்' && DESCRIPTIONS_TA[id]) return DESCRIPTIONS_TA[id];
  if (lang === '中文' && DESCRIPTIONS_ZH[id]) return DESCRIPTIONS_ZH[id];
  if (lang === 'Bahasa Melayu' && DESCRIPTIONS_BM[id]) return DESCRIPTIONS_BM[id];
  if (DESCRIPTIONS_EN[id]) return DESCRIPTIONS_EN[id];

  // Clean fallback: NEVER bold the entire sentence!
  // Bold only the first 2 words as subject, and leave the remaining text plain.
  const text = defaultSentences?.[0] || 'A native wildlife species protected in the sanctuary.';
  const words = text.split(' ');
  if (words.length > 2) {
    return `<b>${words.slice(0, 2).join(' ')}</b> ${words.slice(2).join(' ')}`;
  }
  return text;
}
